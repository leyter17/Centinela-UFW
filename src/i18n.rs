/// Traducción con sustituciones: trf(K::X, lang, &[("%n", "3")])
pub fn trf(k: K, l: Lang, pairs: &[(&str, String)]) -> String {
    let mut s = tr(k, l).to_string();
    for (ph, val) in pairs {
        s = s.replace(ph, val);
    }
    s
}
